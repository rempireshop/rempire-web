#!/usr/bin/env node
/* build-bundles.mjs — turns tools/bundles.config.mjs into
     public/shop/bundles.js   (browser global BUNDLES, loaded by the shop)
     src/data/bundles.json    (server side: order pricing for «bundle:<id>»)
   from public/shop/catalogue2.js.

   Run: node tools/build-bundles.mjs   (or: npm run build:bundles)

   Nothing here is hand-edited — edit tools/bundles.config.mjs and re-run. */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { BUNDLES, DISCOUNT } from "./bundles.config.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Load the generated catalogue (a plain browser script) without a browser. */
export function loadCatalogue(root = ROOT) {
  const src = readFileSync(join(root, "public/shop/catalogue2.js"), "utf8");
  return new Function(src + ";return CATALOGUE")();
}

/** The price of one product at one size index — same rule as the storefront. */
export function sizePrice(p, i) {
  if (p.prices && p.prices.length) return p.prices[Math.min(i || 0, p.prices.length - 1)];
  return p.price;
}

/** Round DOWN to the nearest «,90». The shopper never saves less than promised. */
export function to90(v) {
  let r = Math.floor(v - 0.9) + 0.9;
  if (r > v + 1e-9) r -= 1;
  return Math.round(r * 100) / 100;
}

const money = (n) => Math.round(n * 100) / 100;

/** in < low < out — the worst component decides what the set can promise. */
function worstStock(list) {
  if (list.some((s) => s === "out")) return "out";
  if (list.some((s) => s === "low")) return "low";
  return "in";
}

/**
 * Expand the curated config against a catalogue.
 * Throws on anything a typo can cause, so a broken set never reaches the shop.
 */
export function buildBundles(catalogue, config = BUNDLES, discount = DISCOUNT) {
  const byId = new Map(catalogue.map((p) => [p.id, p]));
  const seenIds = new Set();

  return config.map((b) => {
    if (!/^[a-z0-9][a-z0-9-]*$/.test(b.id)) throw new Error(`bundle id is not a slug: ${b.id}`);
    if (seenIds.has(b.id)) throw new Error(`duplicate bundle id: ${b.id}`);
    seenIds.add(b.id);
    for (const lang of ["RU", "ET", "EN"]) {
      if (!b.title?.[lang]) throw new Error(`bundle ${b.id}: title.${lang} missing`);
      if (!b.desc?.[lang]) throw new Error(`bundle ${b.id}: desc.${lang} missing`);
    }
    if (!Array.isArray(b.items) || b.items.length < 2 || b.items.length > 4) {
      throw new Error(`bundle ${b.id}: needs 2–4 items, got ${b.items?.length}`);
    }

    const seenItems = new Set();
    const items = b.items.map((it) => {
      const p = byId.get(it.id);
      if (!p) throw new Error(`bundle ${b.id}: no such product in the catalogue — ${it.id}`);
      const key = it.id + ":" + (it.size || 0);
      if (seenItems.has(key)) throw new Error(`bundle ${b.id}: ${it.id} listed twice`);
      seenItems.add(key);
      const size = it.size || 0;
      const sizes = p.sizes && p.sizes.length ? p.sizes : [];
      if (size && size >= Math.max(sizes.length, (p.prices || []).length)) {
        throw new Error(`bundle ${b.id}: ${it.id} has no size #${size}`);
      }
      return {
        id: p.id,
        size,
        brand: p.brand,
        name: p.name,
        sizeLabel: sizes.length ? sizes[Math.min(size, sizes.length - 1)] : "",
        price: money(sizePrice(p, size)),
        img: p.img,
        stock: p.stock || "in",
      };
    });

    const sum = money(items.reduce((a, it) => a + it.price, 0));
    const price = to90(sum * (1 - discount));
    return {
      id: b.id,
      cat: b.cat,
      title: { RU: b.title.RU, ET: b.title.ET, EN: b.title.EN },
      desc: { RU: b.desc.RU, ET: b.desc.ET, EN: b.desc.EN },
      items,
      sum,
      price,
      save: money(sum - price),
      pct: Math.round(((sum - price) / sum) * 100),
      images: items.slice(0, 3).map((it) => it.img),
      stock: worstStock(items.map((it) => it.stock)),
    };
  });
}

/* ---- write the two artefacts ---- */
function main() {
  const catalogue = loadCatalogue();
  const out = buildBundles(catalogue);

  const json = JSON.stringify(out, null, 1);
  const header =
    "/* Generated by tools/build-bundles.mjs from tools/bundles.config.mjs —\n" +
    "   do not edit by hand: edit the config and re-run the generator. */\n";
  writeFileSync(join(ROOT, "public/shop/bundles.js"), header + "const BUNDLES = " + json + ";\n", "utf8");

  mkdirSync(join(ROOT, "src/data"), { recursive: true });
  writeFileSync(join(ROOT, "src/data/bundles.json"), json + "\n", "utf8");

  const out90 = out.filter((b) => Math.abs(b.price % 1 - 0.9) > 1e-9);
  if (out90.length) throw new Error("price does not end in ,90: " + out90.map((b) => b.id).join(", "));

  console.log(`bundles: ${out.length} sets`);
  for (const b of out) {
    console.log(
      `  ${b.id.padEnd(18)} ${String(b.items.length)} шт · ` +
        `${b.sum.toFixed(2)} → ${b.price.toFixed(2)} € (−${b.save.toFixed(2)}, ${b.pct}%) · ${b.stock}`,
    );
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
