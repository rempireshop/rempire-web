/* The two robots.txt policies — written by tools/prerender-shop2.mjs (which
   one lands in public/robots.txt is decided there, by $PUBLIC_BASE_URL; see
   its comment and docs/seo.md) and read by tests/robots-policy.test.ts.

   Moved out of the prerender on 09.10.2026, unchanged, when the production
   policy gained its second group: the AI search, assistant and training
   crawlers, named. */

/* The screens behind a basket, a login or a search box, at their addresses
   since 08.10.2026 (src/lib/shop-paths.mjs): the panel and its scanner
   (/admin, /admin/scan — one rule, no language), and the four state screens in
   each language (/checkout covers the receipt at /checkout/done). These are
   Shopify's own Disallow lines, at Shopify's own addresses. The old /shop2/…
   addresses are deliberately NOT here: they answer with a 301 now, and a
   crawler has to be allowed to fetch one to learn where the page went. */
/* The two at the end are ours, not the shop's: /test is the owner's
   acceptance list, /golive the launch checklist (/guide, the manual written
   for him, was removed on 25.10.2026). Each carries a `noindex` meta of its own, which is the
   authoritative half — this list is what keeps them out of the crawl in the
   first place. They were missing until 19.09.2026, and the launch list is the
   one that mattered: audit F18. */
export const NO_INDEX_PATHS = [
  "/admin",
  ...["", "/ru", "/et"].flatMap(pre => ["/checkout", "/cart", "/account", "/search"].map(p => pre + p)),
  "/api/", "/test", "/golive"
];
/* …and inside /api/, the read-only answers a page is drawn from. Googlebot
   renders the page (it reads the DOM app.js leaves, not the file), and with
   all of /api/ disallowed its renderer could not fetch /api/overrides/: the
   live stock, price, «Показывать в магазине» and the owner's own Google texts
   — five products rendered InStock in their JSON-LD while sold out live (SEO
   audit, 08.10.2026). The longest matching rule wins, so these open exactly
   these addresses and nothing else under /api/. */
export const ALLOW_API = ["/api/overrides/", "/api/bundles/", "/api/blog/", "/api/reviews/", "/api/shipping/carriers/"];
export const CLOSED_BOTS = ["facebookexternalhit", "meta-externalagent", "WhatsApp", "Twitterbot", "LinkedInBot",
  "TelegramBot", "Slackbot-LinkExpanding", "Slackbot", "Discordbot", "Applebot", "SkypeUriPreview", "vkShare"];

/* The AI crawlers, by the tokens their makers publish — search (OAI-SearchBot,
   PerplexityBot, Claude-SearchBot), fetches on a user's behalf (ChatGPT-User,
   Perplexity-User, Claude-User), training (GPTBot, ClaudeBot) and the two
   training switches that are not crawlers of their own (Google-Extended,
   Applebot-Extended). Dim, 09.10.2026: the shop is open to all of them,
   training included. Bingbot, which feeds Copilot, is a general crawler and
   is covered by `*`.

   Why name them at all when `*` already lets them in: so the decision is
   written down and stays one edit away. And why the rules are repeated in
   full: a crawler obeys ONLY the most specific group that names it, so a
   group with a bare `Allow: /` would hand these bots the cart, the checkout
   and /api/ that `*` keeps closed. One group, the same lines. */
export const AI_BOTS = ["OAI-SearchBot", "ChatGPT-User", "GPTBot", "PerplexityBot", "Perplexity-User",
  "ClaudeBot", "Claude-SearchBot", "Claude-User", "Google-Extended", "Applebot-Extended"];

const GEN = "# Generated by tools/prerender-shop2.mjs (npm run prerender) — do not edit by hand.\n" +
  "# Which of the two policies lands in public/robots.txt is decided by\n" +
  "# $PUBLIC_BASE_URL; see docs/seo.md.\n";

/** The rule lines every open group carries — the `*` group's, word for word. */
const OPEN_RULES = "Allow: /\n" +
  ALLOW_API.map(p => "Allow: " + p).join("\n") + "\n" +
  "\n# Nothing behind a cart, a payment form or a login belongs in an index.\n" +
  NO_INDEX_PATHS.map(p => "Disallow: " + p).join("\n") + "\n";

/** The production policy, naming `sitemap` (an absolute URL). */
export function robotsProduction(sitemap) {
  return GEN +
    "# REMPIRE — production policy: open, minus everything behind a basket.\n" +
    "\nUser-agent: *\n" + OPEN_RULES +
    "\n# --- AI search, assistant and training crawlers ---\n" +
    "# Named so the decision is written down (open, training included — Dim,\n" +
    "# 09.10.2026). A crawler obeys only the group that names it, so the rules\n" +
    "# are the ones above, repeated.\n" +
    AI_BOTS.map(b => "User-agent: " + b + "\n").join("") + OPEN_RULES +
    `\nSitemap: ${sitemap}\n`;
}

/** The staging policy — closed to every crawler but the link-preview scrapers. */
export function robotsStaging(sitemap) {
  return GEN +
    "# REMPIRE — staging policy: closed to general crawlers, open to the link\n" +
    "# preview scrapers so a shared URL still renders a card. Keeping staging\n" +
    "# out of an index is done by the per-page robots meta and the X-Robots-Tag\n" +
    "# header, both of which are authoritative and neither of which these bots\n" +
    "# act on.\n" +
    "\nUser-agent: *\nDisallow: /\n" +
    "\n# --- link preview scrapers ---\n" +
    CLOSED_BOTS.map(b => `\nUser-agent: ${b}\nAllow: /\n`).join("") +
    "\n# --- what stays closed once the site opens ---\n" +
    "# Listed here so the rule is written down while staging is still shut, and\n" +
    "# so the preview bots above never wander into a cart.\n" +
    "User-agent: *\n" +
    NO_INDEX_PATHS.map(p => "Disallow: " + p).join("\n") + "\n" +
    `\nSitemap: ${sitemap}\n`;
}
