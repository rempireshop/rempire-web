/* The interface dictionary, out of app.min.js and into a file per language.

   ---- why ---------------------------------------------------------------

   public/shop2/app.js opens with `var UI = { ET: {…}, EN: {…} }` — every
   Russian phrase the shop and the panel print, in Estonian and in English:
   about 720 KB of the 2.25 MB app.min.js on 09.10.2026, 3 318 keys a
   language. Every visitor downloaded and parsed both languages before the
   first screen could paint, and a Russian page uses neither (Russian is the
   language the templates are written in; translateTree() does nothing in RU).

   So the build lifts the table out: app.min.js gets
   `var UI = window.__rempireUI || (window.__rempireUI = {});` in its place,
   and each language becomes a file of its own that fills in one key of that
   object — /shop2/ui.et.js and /shop2/ui.en.js. The shell links the one the
   page's language needs (src/lib/seo-head.mjs shellForLang), a Russian page
   links none, and app.js fetches the other one before it re-renders on a
   language switch (uiWant).

   The source stays exactly where it is. app.js is still the one place the
   dictionary is edited, tools/prerender-shop2.mjs still lifts `var UI` out of
   it by source text, and the tests that slice app.js still find it: only the
   built file changes shape.

   ---- the rules -----------------------------------------------------------

   One function, used twice: tools/minify-shop2.mjs writes its output to disk,
   and tools/lib/asset-token.mjs hashes the same output in memory (BUILT_FROM)
   so the ?v= token agrees with itself before and after a build. The table is
   found with js-strip's scanner — a brace inside a string or a regex is never
   counted — and turned into JSON by evaluating the declaration, so what ships
   is exactly the object the browser built before: same keys, same strings,
   the later of two duplicate keys winning, as it always did.

   A script with no `var UI = {` is handed back unchanged with no files: the
   asset-token fixtures are three-line scripts. The build itself refuses a
   real app.js without one (minify-shop2.mjs). */

import { scan } from "./js-strip.mjs";

/** The window property the built files share. */
export const UI_GLOBAL = "__rempireUI";

const OPEN = "var UI = {";

/** [start, end) of the whole `var UI = {…};` statement, or null. */
export function uiSpan(src) {
  let pos = 0;
  let start = -1;
  let depth = 0;
  for (const t of scan(src)) {
    if (t.t === "code") {
      for (let i = 0; i < t.v.length; i++) {
        if (start < 0) {
          if (t.v.startsWith(OPEN, i) && !/[\w$.]/.test(src[pos + i - 1] || "")) {
            start = pos + i;
            depth = 1;
            i += OPEN.length - 1;
          }
          continue;
        }
        const ch = t.v[i];
        if (ch === "{") depth++;
        else if (ch === "}" && --depth === 0) {
          let end = pos + i + 1;
          if (src[end] === ";") end++;
          return [start, end];
        }
      }
    }
    pos += t.v.length;
  }
  return null;
}

/** The first line of each language's file. */
function header(lang) {
  return "/* Generated by tools/minify-shop2.mjs from `var UI` in public/shop2/app.js — the " +
    (lang === "ET" ? "Estonian" : lang === "EN" ? "English" : lang) +
    " interface dictionary. Edit app.js, never this file. */\n";
}

/**
 * `{ app, files, ui }` — the script with its table replaced by the shared
 * global, one file's text per language (`files.ET`, `files.EN`), and the
 * table itself. With no table: the script as it came, `files` empty.
 */
export function liftUi(script) {
  const src = String(script);
  const span = uiSpan(src);
  if (!span) return { app: src, files: {}, ui: null };
  const decl = src.slice(span[0], span[1]);
  const ui = new Function(decl + "\nreturn UI;")();
  const files = {};
  for (const lang of Object.keys(ui)) {
    files[lang] = header(lang) +
      "(window." + UI_GLOBAL + " = window." + UI_GLOBAL + " || {})." + lang + " = " + JSON.stringify(ui[lang]) + ";\n";
  }
  const app = src.slice(0, span[0]) + "var UI = window." + UI_GLOBAL + " || (window." + UI_GLOBAL + " = {});" + src.slice(span[1]);
  return { app, files, ui };
}
