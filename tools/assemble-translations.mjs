/* Collect the translation fleet's chunk outputs into the four language files
   the shop loads:
     public/shop/content.ru.js  — var CONTENT_RU
     public/shop/content.et.js  — var CONTENT_ET
     public/shop/legal.ru.js    — var LEGAL_RU
     public/shop/legal.et.js    — var LEGAL_ET
   Translated HTML goes through the same sanitizer as the source — belt and
   braces, the source was already clean. */

import { readFile, writeFile, readdir } from "node:fs/promises";
import path from "node:path";

const ROOT = "C:/Users/Dmitri.MARKIT/source/repos/rempire-web";
const TR = "C:/Users/DMITRI~1.MAR/AppData/Local/Temp/claude/C--Users-Dmitri-MARKIT-source-repos-Rempire/d86fba33-c4c4-4dad-a0f6-a1d47ab1c4e3/scratchpad/tr";

function sanitize(html) {
  if (!html) return "";
  let s = String(html);
  s = s.replace(/<(script|style|iframe|object|embed|form|svg)[\s\S]*?<\/\1>/gi, "");
  s = s.replace(/<(img|source|video|audio|picture)\b[^>]*>/gi, "");
  // Stray <meta charset> tags ride along in the supplier HTML and split words
  // in the rendered page ("a<meta>\n<span>nnab" showed as "a nnab"). Eat the
  // tag AND the whitespace after it so the two halves join back up; the space
  // before it is kept, so a tag between two real words stays two words.
  s = s.replace(/<meta\b[^>]*>\s*/gi, "");
  s = s.replace(/\son\w+="[^"]*"/gi, "").replace(/\son\w+='[^']*'/gi, "");
  s = s.replace(/\s(style|class|id|dir|data-[\w-]+)="[^"]*"/gi, "");
  s = s.replace(/\s(style|class|id|dir|data-[\w-]+)='[^']*'/gi, "");
  s = s.replace(/\r/g, "").trim();
  return s;
}

const files = (await readdir(TR)).sort();
const langs = { ru: {}, et: {} };
for (const f of files) {
  const m = f.match(/^out-(\d+)\.(ru|et)\.json$/);
  if (!m) continue;
  const j = JSON.parse(await readFile(path.join(TR, f), "utf8"));
  // chunks were cut before the ASCII-id rule — apply the same strip here
  for (const [id, html] of Object.entries(j)) langs[m[2]][id.replace(/[^\x20-\x7e]/g, "")] = sanitize(html);
}

const enSrc = await readFile(path.join(ROOT, "public/shop/content.js"), "utf8");
const CONTENT = new Function(enSrc + "\nreturn CONTENT;")();
const report = { en: Object.keys(CONTENT).length };
for (const l of ["ru", "et"]) {
  const missing = Object.keys(CONTENT).filter(id => !langs[l][id]);
  report[l] = { have: Object.keys(langs[l]).length, missing };
  await writeFile(path.join(ROOT, "public/shop/content." + l + ".js"),
    "/* Generated by tools/assemble-translations.mjs — AI translation of the\n" +
    "   shop's own EN descriptions (fleet of 02.09.2026), pending native proofread. */\n" +
    "var CONTENT_" + l.toUpperCase() + " = " + JSON.stringify(langs[l]) + ";\n", "utf8");
}

for (const l of ["ru", "et"]) {
  try {
    const j = JSON.parse(await readFile(path.join(TR, "legal." + l + ".json"), "utf8"));
    const clean = {};
    for (const [slug, pg] of Object.entries(j)) clean[slug] = { title: pg.title, html: sanitize(pg.html) };
    await writeFile(path.join(ROOT, "public/shop/legal." + l + ".js"),
      "/* Generated by tools/assemble-translations.mjs — AI translation of the\n" +
      "   policy pages, to be replaced by lawyer-reviewed versions before launch. */\n" +
      "var LEGAL_" + l.toUpperCase() + " = " + JSON.stringify(clean) + ";\n", "utf8");
    report["legal_" + l] = Object.keys(clean);
  } catch (e) { report["legal_" + l] = "MISSING: " + e.message; }
}

