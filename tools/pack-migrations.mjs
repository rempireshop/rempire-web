/* Embeds db/migrations/*.sql into src/db/migrations.generated.ts so the
   deployed app (serverless, no repo on disk) can run pending migrations
   itself via POST /api/admin/migrate. Runs in `prebuild`; idempotent. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DIR = path.join(HERE, "..", "db", "migrations");
const OUT = path.join(HERE, "..", "src", "db", "migrations.generated.ts");

const files = fs.readdirSync(DIR).filter((f) => f.endsWith(".sql")).sort();
/* LF, always. A Windows checkout with core.autocrlf=true has every .sql on
   disk in CRLF, so reading them raw embedded \r\n into each string and rewrote
   all 38 entries of the generated file on a machine where nothing had changed.
   Postgres does not care either way; a 38-file diff in a commit that added one
   migration does. No-op on a checkout that already has LF. */
const entries = files.map((name) => ({
  name,
  sql: fs.readFileSync(path.join(DIR, name), "utf8").replace(/\r\n/g, "\n"),
}));
const body =
  "/* Generated by tools/pack-migrations.mjs from db/migrations — do not edit. */\n" +
  "export const MIGRATIONS: ReadonlyArray<{ name: string; sql: string }> = " +
  JSON.stringify(entries, null, 2) + ";\n";
fs.mkdirSync(path.dirname(OUT), { recursive: true });
const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
if (prev !== body) fs.writeFileSync(OUT, body, "utf8");
console.log(`pack-migrations: ${files.length} file(s)${prev === body ? " (unchanged)" : ""}`);
