const TR = "C:/Users/DMITRI~1.MAR/AppData/Local/Temp/claude/C--Users-Dmitri-MARKIT-source-repos-Rempire/d86fba33-c4c4-4dad-a0f6-a1d47ab1c4e3/scratchpad/tr";

function sanitize(html) {
  if (!html) return "";
  let s = String(html);
  s = s.replace(/<(script|style|iframe|object|embed|form|svg)[\s\S]*?<\/\1>/gi, "");
  s = s.replace(/<(img|source|video|audio|picture)\b[^>]*>/gi, "");
  // Stray <meta charset> tags in supplier HTML split words when rendered
  // ("a<meta ...><span>dds" showed as "a dds"); eat the tag and the whitespace after it.
  s = s.replace(/<meta\b[^>]*>\s*/gi, "");
  s = s.replace(/\son\w+="[^"]*"/gi, "").replace(/\son\w+='[^']*'/gi, "");
  s = s.replace(/\s(style|class|id|dir|data-[\w-]+)="[^"]*"/gi, "");
  s = s.replace(/\s(style|class|id|dir|data-[\w-]+)='[^']*'/gi, "");
  s = s.replace(/<a\b[^>]*href="(javascript:)[^"]*"[^>]*>/gi, "<a>");
  s = s.replace(/<span>\s*<\/span>/g, "");
  s = s.replace(/<p>(\s|&nbsp;)*<\/p>/gi, "");
  s = s.replace(/\r/g, "").replace(/\n{3,}/g, "\n\n").trim();
  return s;
}

// current CONTENT keeps the two draft perfumes absent from the active export
const oldSrc = await readFile(path.join(ROOT, "public/shop/content.js"), "utf8");
const OLD = new Function(oldSrc + "\nreturn CONTENT;")();

const normId = h => h.replace(/[^\x20-\x7e]/g, ""); // same rule as the catalogue build
const bodies = JSON.parse(await readFile(path.join(ROOT, "tools/harvest/bodies-en.json"), "utf8"));
const content = {};
for (const [k, v] of Object.entries(OLD)) if (k === normId(k)) content[k] = sanitize(v); // re-sanitise carried-over entries; drop pre-rule ® keys
let fresh = 0;
for (const [rawId, html] of Object.entries(bodies)) {
  const id = normId(rawId);
  if (content[id]) continue; // harvested version already sanitized and shipped
  const clean = sanitize(html);
  if (clean.length > 40) { content[id] = clean; fresh++; }
}

const catSrc = await readFile(path.join(ROOT, "public/shop/catalogue2.js"), "utf8");
const CATALOGUE = new Function(catSrc + "\nreturn CATALOGUE;")();
const missing = CATALOGUE.filter(p => !content[p.id]).map(p => p.id);

await writeFile(path.join(ROOT, "public/shop/content.js"),
  "/* Generated by tools/build-content-full.mjs — the shop's own English\n" +
  "   descriptions for the full active catalogue. Do not edit by hand. */\n" +
  "var CONTENT = " + JSON.stringify(content) + ";\n", "utf8");

// ---------- translation chunks ----------
// never rewrite chunks the fleet is already reading — first run only
await mkdir(TR, { recursive: true });
const ids = CATALOGUE.filter(p => content[p.id]).map(p => p.id);
const SIZE = 12;
let chunks = 0;
let chunksWritten = false;
try { await readFile(path.join(TR, "chunk-00.json")); } catch (e) { chunksWritten = true; }
for (let i = 0; i < ids.length; i += SIZE) {
  if (chunksWritten) {
    const chunk = {};
    for (const id of ids.slice(i, i + SIZE)) chunk[id] = content[id];
    await writeFile(path.join(TR, "chunk-" + String(chunks).padStart(2, "0") + ".json"),
      JSON.stringify(chunk, null, 1), "utf8");
  }
  chunks++;
}
const legalSrc = await readFile(path.join(ROOT, "public/shop/legal.js"), "utf8");
const LEGAL = new Function(legalSrc + "\nreturn LEGAL;")();
await writeFile(path.join(TR, "legal.json"), JSON.stringify(LEGAL, null, 1), "utf8");

