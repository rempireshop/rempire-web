function sanitize(html) {
  if (!html) return "";
  let s = String(html);
  s = s.replace(/<(script|style|iframe|object|embed|form|svg)[\s\S]*?<\/\1>/gi, "");
  s = s.replace(/<(img|source|video|audio|picture)\b[^>]*>/gi, "");
  s = s.replace(/\son\w+="[^"]*"/gi, "").replace(/\son\w+='[^']*'/gi, "");
  s = s.replace(/\s(style|class|id|dir|data-[\w-]+)="[^"]*"/gi, "");
  s = s.replace(/\s(style|class|id|dir|data-[\w-]+)='[^']*'/gi, "");
  s = s.replace(/<a\b[^>]*href="(javascript:)[^"]*"[^>]*>/gi, "<a>");
  // meta spans Shopify's editor loves
  s = s.replace(/<span>\s*<\/span>/g, "");
  s = s.replace(/<p>(\s|&nbsp;)*<\/p>/gi, "");
  s = s.replace(/\r/g, "").replace(/\n{3,}/g, "\n\n").trim();
  return s;
}

