function csvBody(handle) {
  const i = csv.indexOf("\n" + handle + ",");
  if (i < 0) return null;
  // Body is the 3rd field, quoted; parse just this row's start
  const row = csv.slice(i + 1, i + 60000);
  const m = row.match(/^[^,]*,(?:"[^"]*"|[^,]*),"((?:[^"]|"")*)"/s);
  return m ? m[1].replace(/""/g, '"') : null;
}
